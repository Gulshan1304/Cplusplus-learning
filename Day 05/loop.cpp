#include<iostream>
using namespace std;
// for loop
int main () {
    for (int i = 0; i < 5; i++) {
        cout << i << endl ;
    }
    // while loop
    int j = 0;
    while (j < 5) {
        cout << j << endl ;
        j++;
    }
    // do while loop
    int k = 0;
    do {
        cout << k << endl ;
        k++;
    } while (k < 5);
return 0;
}   