#include <iostream>
#include <cmath>
using namespace std;

int main() {

    // sqrt() - Square Root
    cout << "sqrt(64) = " << sqrt(64) << endl;

    // pow() - Power
    cout << "pow(2, 5) = " << pow(2, 5) << endl;

    // abs() - Absolute Value
    cout << "abs(-25) = " << abs(-25) << endl;

    // ceil() - Round Up
    cout << "ceil(4.2) = " << ceil(4.2) << endl;

    // floor() - Round Down
    cout << "floor(4.8) = " << floor(4.8) << endl;

    // round() - Round to Nearest Integer
    cout << "round(4.5) = " << round(4.5) << endl;

    // cbrt() - Cube Root
    cout << "cbrt(125) = " << cbrt(125) << endl;

    // fmax() - Maximum
    cout << "fmax(10, 20) = " << fmax(10, 20) << endl;

    // fmin() - Minimum
    cout << "fmin(10, 20) = " << fmin(10, 20) << endl;

    // sin() - Sine
    cout << "sin(0) = " << sin(0) << endl;

    // cos() - Cosine
    cout << "cos(0) = " << cos(0) << endl;

    // tan() - Tangent
    cout << "tan(0) = " << tan(0) << endl;

    // log() - Natural Logarithm
    cout << "log(10) = " << log(10) << endl;

    // log10() - Base-10 Logarithm
    cout << "log10(1000) = " << log10(1000) << endl;

    // exp() - e^x
    cout << "exp(1) = " << exp(1) << endl;

    return 0;
}